"""Generate the DeepCell full-split (91/27) injection config from Achard's
reference config (SPEC 0044).

Reads Achard's reference config verbatim from his fork's training ref
(``origin/cy/pretrained_feats_train:scripts/deepcell/sam21_deepcell.yaml``),
applies an auditable substitution list (backbone swap + checkpoint insert;
data root for train/val; the ``16_corrected`` ground-truth mapping; outdir,
cachedir, and run name), asserts the transformed config lists exactly 91
train / 27 val / 12 test sequences, and writes
``etultra_dynaclr_deepcell_fullsplit.yaml`` next to the existing configs.

The entry-count assertion encodes SPEC 0044's acceptance criterion AC1:
the generated config must match the reference's protocol-matched split
sizes (Achard thesis Table 2.1: 130 videos, train 91 / val 27 / test 12).

Usage (run on the cluster after ``<data-root>`` has been decided and
populated; see the labbook entry ``2026-10-21_deepcell_fullsplit_head_retrain.md``):

    python3 benchmark_ssl/slurm/configs/generate_deepcell_fullsplit_config.py \\
        --fork-repo cyril_trackastra \\
        --data-root /data/cat/ws/lest161c-ssl_cell_tracking/data/celltracking/deepcell_full
"""

import argparse
import pathlib
import subprocess

FORK_REF = "origin/cy/pretrained_feats_train"
REFERENCE_CONFIG = "scripts/deepcell/sam21_deepcell.yaml"
OUTPUT_DIR = pathlib.Path(__file__).resolve().parent
OUTPUT_NAME = "etultra_dynaclr_deepcell_fullsplit.yaml"
BENCH = "/data/cat/ws/lest161c-ssl_cell_tracking/bench-transformer-cell-tracking"
CHECKPOINT = f"{BENCH}/benchmark_ssl/results/checkpoints/cnn_bn100k_step100000.pt"
# The verified 12-sequence evaluation split, unchanged from the 28/2 arm:
# training never touches it, so it keeps pointing at the existing copy.
TEST_DATA_DIR = "/data/cat/ws/mawe985g-data/data/celltracking/deepcell"

EXPECTED_COUNTS = {"input_train": 91, "input_val": 27, "input_test": 12}

# Substitution order is irrelevant: the patterns are pairwise disjoint
# prefixes of Achard's paths (his tree splits into deepcell_full/ and
# deepcell_orig/).
SUBSTITUTIONS_HEAD = [
    # Achard swapped in the corrected ground truth for train/16 (he fixed two
    # pixels in frame 23, mask 42 -> 41; thesis Sec. 2). We map it to the
    # plain train/16 of the copied split and carry the verification duty over
    # to the cluster checklist (spot-check before training).
    ("/backup/achard/CTC_DATA/deepcell/deepcell_orig/train/16_corrected",
     "{data_root}/train/16"),
    ("/backup/achard/CTC_DATA/deepcell/deepcell_full/test",
     f"{TEST_DATA_DIR}/test"),
    ("/backup/achard/CTC_DATA/deepcell/deepcell_full/train",
     "{data_root}/train"),
    ("/backup/achard/CTC_DATA/deepcell/deepcell_full/val",
     "{data_root}/val"),
    ("pretrained_feats_model: facebook/sam2.1-hiera-base-plus",
     "pretrained_feats_model: dynaclr-scaledcnn"),
    ("cachedir: /backup/achard/cache", f"cachedir: {BENCH}/.cache/etultra_fullsplit"),
    ("outdir: /home/achard/trastra_v3_deepcell",
     f"outdir: {BENCH}/benchmark_ssl/results/etultra_runs/deepcell_fullsplit"),
    ("name: deepcell_sam21_aug", "name: deepcell_sam21_aug_fullsplit"),
]

HEADER = """\
# DRAFT - generated by generate_deepcell_fullsplit_config.py (SPEC 0044)
# from Achard's {ref}: {source}
# Deviations from the reference: backbone -> dynaclr-scaledcnn; added
# pretrained_model_path; data root -> {data_root} (full 91/27 split,
# copied into our workspace); outdir/cachedir/name repointed. The test
# split keeps pointing at the existing verified mawe985g copy.
# Before sbatch: verify <data-root>/train holds 91 sequences and
# <data-root>/val holds 27, and that train/16 carries the corrected
# ground truth (Achard fixed two pixels in frame 23, mask 42 -> 41).
"""


def read_reference(fork_repo: str) -> str:
    """Return Achard's reference config text from the fork's training ref.

    Parameters
    ----------
    fork_repo: str
        Path to a local clone of ``github.com/C-Achard/trackastra`` whose
        ``origin`` carries the ``cy/pretrained_feats_train`` branch.

    Returns
    -------
    str
        The raw yaml text of the reference DeepCell config.

    Raises
    ------
    subprocess.CalledProcessError
        If the fork repo or the reference branch/path cannot be read.
    """
    return subprocess.check_output(
        ["git", "-C", fork_repo, "show", f"{FORK_REF}:{REFERENCE_CONFIG}"],
        text=True,
    )


def count_input_entries(source_text: str, key: str) -> int:
    """Count the list entries under a top-level yaml key.

    Counts consecutive ``- <path>`` lines following the ``key:`` line,
    stopping at the next non-list line. Works on the flat list layout
    used by all Trackastra configs.

    Parameters
    ----------
    source_text: str
        The config text to inspect.
    key: str
        The top-level key whose list entries are counted
        (``input_train``, ``input_val``, or ``input_test``).

    Returns
    -------
    int
        The number of list entries under ``key``.
    """
    in_section = False
    count = 0
    for line in source_text.splitlines():
        stripped = line.strip()
        if stripped.startswith(f"{key}:"):
            in_section = True
            continue
        if in_section:
            if stripped.startswith("- "):
                count += 1
            elif stripped and not stripped.startswith("#"):
                in_section = False
    return count


def transform(source_text: str, data_root: str) -> str:
    """Apply the substitution list and insert the checkpoint path line.

    Parameters
    ----------
    source_text: str
        Achard's reference config text.
    data_root: str
        Cluster directory holding the copied full split
        (``<data-root>/train`` with 91 sequences, ``<data-root>/val``
        with 27).

    Returns
    -------
    str
        The transformed config text, with the audit header prepended.

    Raises
    -------
    ValueError
        If the transformed config does not list exactly 91 train, 27
        val, and 12 test sequences (SPEC 0044 AC1).
    """
    lines_out = []
    for line in source_text.splitlines():
        for old, new in SUBSTITUTIONS_HEAD:
            line = line.replace(old, new.format(data_root=data_root))
        lines_out.append(line)
        if line.startswith("pretrained_feats_model:"):
            lines_out.append(f"pretrained_model_path: {CHECKPOINT}")
    transformed = "\n".join(lines_out) + "\n"

    counts = {
        key: count_input_entries(transformed, key) for key in EXPECTED_COUNTS
    }
    if counts != EXPECTED_COUNTS:
        raise ValueError(
            "Transformed config split sizes do not match the reference "
            f"protocol (expected {EXPECTED_COUNTS}, found {counts}); "
            "refusing to write it."
        )
    header = HEADER.format(ref=FORK_REF, source=REFERENCE_CONFIG,
                           data_root=data_root)
    return header + transformed


def main() -> None:
    """Parse CLI arguments, transform the reference config, write the output."""
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--fork-repo", required=True,
        help="Path to the local clone of C-Achard/trackastra.",
    )
    parser.add_argument(
        "--data-root", required=True,
        help="Cluster directory with the copied full split "
             "(<data-root>/train = 91 seqs, <data-root>/val = 27 seqs).",
    )
    arguments = parser.parse_args()

    source_text = read_reference(arguments.fork_repo)
    output_text = transform(source_text, arguments.data_root)
    output_path = OUTPUT_DIR / OUTPUT_NAME
    output_path.write_text(output_text)
    print(f"wrote {output_path}")
    for key in EXPECTED_COUNTS:
        print(f"  {key}: {count_input_entries(output_text, key)} entries")


if __name__ == "__main__":
    main()
