"""Generate our Et-Ultra training configs from Achard's, changing only the
backbone and paths (SPEC 0032).

Deriving our configs from his by an auditable substitution list avoids silent
drift from his trained-benchmark protocol. Usage:

    python3 benchmark_ssl/slurm/configs/generate_etultra_configs.py \\
        --fork-repo /home/leonard.starke@mediainterface.de/cyril_trackastra
"""

import argparse
import pathlib
import subprocess

FORK_REF = "origin/cy/pretrained_feats_train"
OUTPUT_DIR = pathlib.Path(__file__).resolve().parent
BENCH = "/data/cat/ws/lest161c-ssl_cell_tracking/bench-transformer-cell-tracking"
DATA_DIR = "/data/cat/ws/mawe985g-data/data/celltracking"
CHECKPOINT = f"{BENCH}/benchmark_ssl/results/checkpoints/cnn_bn100k_step100000.pt"

REFERENCE_CONFIGS = {
    "scripts/sam21_aug_bacteria.yaml": "etultra_dynaclr_bacteria.yaml",
    "scripts/deepcell/sam21_deepcell.yaml": "etultra_dynaclr_deepcell.yaml",
}

SUBSTITUTIONS = [
    ("pretrained_feats_model: facebook/sam2.1-hiera-base-plus", "pretrained_feats_model: dynaclr-scaledcnn"),
    ("/backup/achard/CTC_DATA", DATA_DIR),
    ("deepcell/deepcell_full", "deepcell"),
    ("deepcell/deepcell_orig/train/16_corrected", "deepcell/train/16"),
    ("outdir: /home/achard/trastra_v2", f"outdir: {BENCH}/benchmark_ssl/results/etultra_runs/bacteria"),
    ("outdir: /home/achard/trastra_v3_deepcell", f"outdir: {BENCH}/benchmark_ssl/results/etultra_runs/deepcell"),
    ("cachedir: /backup/achard/cache", f"cachedir: {BENCH}/.cache/etultra"),
]

HEADER = """\
# DRAFT - generated by generate_etultra_configs.py from Achard's
# {ref}: {source}
# Deviations: backbone -> dynaclr-scaledcnn; added pretrained_model_path;
# data/outdir/cachedir repointed to our cluster. Blocked on T0 (bridge) + T3 (smoke).
# NOTE: deepcell_orig/train/16_corrected was mapped to deepcell/train/16; verify
# that the cluster's train/16 holds the corrected ground truth.
"""


def read_reference(fork_repo, path):
    """Return the reference config text from the fork's training ref."""
    return subprocess.check_output(
        ["git", "-C", fork_repo, "show", f"{FORK_REF}:{path}"], text=True
    )


def transform(source_text, source_path):
    """Apply the substitution list and insert the checkpoint path line."""
    lines_out = []
    for line in source_text.splitlines():
        for old, new in SUBSTITUTIONS:
            line = line.replace(old, new)
        # Achard's config lists trpL/150303-08, which the thesis itself omits
        # (bad detection masks) and which our data stores as *_BAD; drop it.
        if line.strip().endswith("vanliet/trpL/150303-08") or line.strip().endswith("vanvliet/trpL/150303-08"):
            continue
        lines_out.append(line)
        if line.startswith("pretrained_feats_model:"):
            lines_out.append(f"pretrained_model_path: {CHECKPOINT}")
    return HEADER.format(ref=FORK_REF, source=source_path) + "\n".join(lines_out) + "\n"


def main():
    """Read each reference config, transform it, and write our config."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fork-repo", required=True)
    args = parser.parse_args()
    for source_path, output_name in REFERENCE_CONFIGS.items():
        source_text = read_reference(args.fork_repo, source_path)
        (OUTPUT_DIR / output_name).write_text(transform(source_text, source_path))
        print(f"wrote {OUTPUT_DIR / output_name}")


if __name__ == "__main__":
    main()
